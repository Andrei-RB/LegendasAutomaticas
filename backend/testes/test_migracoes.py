import pytest
from pydantic import SecretStr
from sqlalchemy import create_engine, text
from sqlalchemy import inspect as sa_inspect

from alembic import command, util
from app.nucleo.config import settings

TABELAS = {
    "usuarios",
    "videos",
    "analises",
    "execucoes_etapa",
    "candidatos",
    "julgamentos",
    "cortes",
    "documentos_legenda",
    "modelos_legenda",
    "fontes",
    "exportacoes",
    "textos_postagem",
    "cache_hashtags",
    "hashtags_usuario",
    "chamadas_ia",
    "feedback",
}


def _tabelas(url: str) -> set[str]:
    motor = create_engine(url)
    try:
        return set(sa_inspect(motor).get_table_names())
    finally:
        motor.dispose()


def test_upgrade_head_cria_as_16_tabelas(banco_limpo, config_alembic):
    command.upgrade(config_alembic(banco_limpo), "head")
    assert _tabelas(banco_limpo) == TABELAS | {"alembic_version"}


def test_downgrade_base_remove_tudo_e_upgrade_repete(banco_limpo, config_alembic):
    cfg = config_alembic(banco_limpo)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert _tabelas(banco_limpo) <= {"alembic_version"}
    command.upgrade(cfg, "head")
    assert _tabelas(banco_limpo) == TABELAS | {"alembic_version"}


def test_alembic_check_sem_diferencas_apos_upgrade(banco_migrado, config_alembic):
    command.check(config_alembic(banco_migrado))


def test_alembic_check_detecta_default_de_servidor_alterado(banco_migrado, config_alembic):
    motor = create_engine(banco_migrado, isolation_level="AUTOCOMMIT")
    try:
        with motor.connect() as con:
            con.execute(text("ALTER TABLE videos ALTER COLUMN expira_em SET DEFAULT now()"))
    finally:
        motor.dispose()
    with pytest.raises(util.AutogenerateDiffsDetected):
        command.check(config_alembic(banco_migrado))


def test_upgrade_usa_database_url_quando_ini_sem_url(banco_limpo, config_alembic, monkeypatch):
    cfg = config_alembic(banco_limpo)
    cfg.set_main_option("sqlalchemy.url", "")
    monkeypatch.setattr(settings, "DATABASE_URL", SecretStr(banco_limpo))
    command.upgrade(cfg, "head")
    assert _tabelas(banco_limpo) == TABELAS | {"alembic_version"}
